//! Generates `gateway.rs` in `OUT_DIR`, which `src/lib.rs` includes: the enum `Rpc`, the
//! table `ROUTES` and the function `call`, from the `google.api.http` option of every
//! method of `jobscheduler.v1.JobService` in js-proto's descriptor set
//! (`js_proto::FILE_DESCRIPTOR_SET`).
//!
//! The options are read and checked by `src/annotation.rs`, the module the crate's tests run
//! over test descriptors. A method whose option the gateway does not serve fails the build
//! with the method's name and the fault, and so does a service without one annotated
//! method. `call` calls each annotated method of the generated trait by its snake-case name,
//! with its request and response types from `js_proto::v1`.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

use prost_reflect::DescriptorPool;

#[allow(
    dead_code,
    reason = "the library and its tests use items of the module the build script does not"
)]
#[path = "src/annotation.rs"]
mod annotation;

use annotation::{RouteSpec, Verb};

/// The service the gateway serves.
const SERVICE: &str = "jobscheduler.v1.JobService";

/// The package prefix of the service's messages, whose Rust types are in `js_proto::v1`.
const PACKAGE: &str = "jobscheduler.v1.";

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/annotation.rs");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?);
    let pool = DescriptorPool::decode(js_proto::FILE_DESCRIPTOR_SET)?;
    let routes = annotation::routes(&pool, SERVICE).map_err(|err| err.to_string())?;
    if routes.is_empty() {
        return Err(format!("{SERVICE}: no method carries a google.api.http option").into());
    }
    std::fs::write(out.join("gateway.rs"), render(&routes)?)?;
    Ok(())
}

/// The Rust of `routes`.
fn render(routes: &[RouteSpec]) -> Result<String, Box<dyn Error>> {
    let mut code = String::new();
    writeln!(
        code,
        "// Generated by build.rs from the google.api.http options of {SERVICE}."
    )?;
    writeln!(code)?;
    writeln!(
        code,
        "/// A method of `{SERVICE}` that has a route: one per annotated method, in the order"
    )?;
    writeln!(code, "/// of the service definition.")?;
    writeln!(code, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]")?;
    writeln!(code, "pub enum Rpc {{")?;
    for route in routes {
        writeln!(
            code,
            "    /// `{}`, served at `{} {}`.",
            route.rpc,
            route.verb.as_str(),
            route.template
        )?;
        writeln!(code, "    {},", route.rpc)?;
    }
    writeln!(code, "}}")?;
    writeln!(code)?;
    writeln!(code, "impl Rpc {{")?;
    writeln!(
        code,
        "    /// The method's name in the service definition, such as `{}`.",
        routes[0].rpc
    )?;
    writeln!(code, "    #[must_use]")?;
    writeln!(code, "    pub const fn name(self) -> &'static str {{")?;
    writeln!(code, "        match self {{")?;
    for route in routes {
        writeln!(code, "            Self::{0} => {0:?},", route.rpc)?;
    }
    writeln!(code, "        }}")?;
    writeln!(code, "    }}")?;
    writeln!(code, "}}")?;
    writeln!(code)?;
    writeln!(
        code,
        "/// The routes of the gateway, one per annotated method of `{SERVICE}`, in the order"
    )?;
    writeln!(code, "/// of the service definition.")?;
    writeln!(code, "pub const ROUTES: &[Route] = &[")?;
    for route in routes {
        writeln!(code, "    Route {{")?;
        writeln!(code, "        verb: {},", verb(route.verb))?;
        writeln!(code, "        template: {:?},", route.template)?;
        writeln!(code, "        rpc: Rpc::{},", route.rpc)?;
        writeln!(code, "        body: {},", route.body)?;
        writeln!(code, "        status: {},", route.status)?;
        writeln!(code, "        input: {:?},", route.input)?;
        writeln!(code, "        output: {:?},", route.output)?;
        writeln!(code, "    }},")?;
    }
    writeln!(code, "];")?;
    writeln!(code)?;
    writeln!(
        code,
        "/// Calls the method `rpc` of `service` with `input`, a message of its request type,"
    )?;
    writeln!(
        code,
        "/// and answers its response as a message of `output` (see [`decode_as`] and [`answer_of`])."
    )?;
    writeln!(
        code,
        "async fn call<T: ::js_proto::v1::job_service_server::JobService>("
    )?;
    writeln!(code, "    service: &T,")?;
    writeln!(code, "    rpc: Rpc,")?;
    writeln!(code, "    input: ::prost_reflect::DynamicMessage,")?;
    writeln!(code, "    output: &::prost_reflect::MessageDescriptor,")?;
    writeln!(
        code,
        ") -> ::core::result::Result<::prost_reflect::DynamicMessage, Answer> {{"
    )?;
    writeln!(code, "    match rpc {{")?;
    for route in routes {
        let request = message_type(&route.input)?;
        writeln!(code, "        Rpc::{} => {{", route.rpc)?;
        writeln!(
            code,
            "            let request = decode_as::<{request}>(&input)?;"
        )?;
        writeln!(
            code,
            "            let response = service.{}(::tonic::Request::new(request)).await;",
            snake_case(&route.rpc)
        )?;
        writeln!(
            code,
            "            answer_of(output, response.map(|response| \
             ::prost::Message::encode_to_vec(response.get_ref())))"
        )?;
        writeln!(code, "        }}")?;
    }
    writeln!(code, "    }}")?;
    writeln!(code, "}}")?;
    Ok(code)
}

/// The Rust spelling of a verb in the generated table.
fn verb(verb: Verb) -> &'static str {
    match verb {
        Verb::Get => "Verb::Get",
        Verb::Post => "Verb::Post",
    }
}

/// The Rust type of the message `full_name`, which must be a top-level message of
/// [`PACKAGE`].
fn message_type(full_name: &str) -> Result<String, Box<dyn Error>> {
    let name = full_name
        .strip_prefix(PACKAGE)
        .filter(|name| !name.contains('.'))
        .ok_or_else(|| format!("{full_name} is not a top-level message of {PACKAGE}"))?;
    Ok(format!("::js_proto::v1::{name}"))
}

/// The snake-case name the generated trait gives a method: `GetJob` is `get_job`.
fn snake_case(name: &str) -> String {
    let mut snake = String::new();
    for (index, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if index > 0 {
                snake.push('_');
            }
            snake.push(c.to_ascii_lowercase());
        } else {
            snake.push(c);
        }
    }
    snake
}

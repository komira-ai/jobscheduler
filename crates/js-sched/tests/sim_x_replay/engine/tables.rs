//! Integer quantile tables: the only way the truth model draws from a lognormal.
//!
//! A table holds [`LEN`] values in parts per million, one per quantile of a lognormal
//! with mean 1. Entry `i` is
//!
//! ```text
//! round(10^6 * exp(-s^2 / 2 + s * z((i + 1/2) / 1024)))      z = the standard normal quantile
//! ```
//!
//! for the table's `s`, then rescaled once (and rounded) so that the mean of the
//! distribution [`draw`] actually samples, interpolation included, is 1 within a few parts
//! in a million. The tables were generated offline from that formula and are committed as
//! integers, so no float is read, computed or compared when the simulation runs.
//!
//! | table | `s` | used for |
//! |---|---|---|
//! | [`LN32`] | 0.32 | the burst of a 5 s window (p99 near 2.0) |
//! | [`LN15`] | 0.15 | the per-minute noise on a run's shape |
//! | [`LN2245`] | 0.2245 | a hand-made world's run means (median over P90 near 0.75) |

/// Entries in a table.
pub const LEN: usize = 1024;

/// A quantile table: ppm values, non-decreasing.
pub type Table = [u32; LEN];

/// One million: the value 1.0 in a table.
pub const ONE_PPM: u64 = 1_000_000;

/// How many bits of a draw [`draw`] reads: ten pick the entry, ten interpolate.
const DRAW_BITS: u32 = 20;

/// The value, in ppm, at the quantile named by the top 20 bits of `u`.
///
/// The bits split into an entry `i` (the high ten) and a fraction `f / 1024` (the low
/// ten); the value is the straight line from entry `i` to entry `i + 1` (the last entry
/// is held). `u` should come from [`super::truth::mix`], whose output is uniform.
pub fn draw(table: &Table, u: u64) -> u64 {
    let r = u >> (u64::BITS - DRAW_BITS);
    // At most 1023: ten bits.
    let i = (r >> 10) as usize;
    let f = r & 1023;
    let lo = u64::from(table[i]);
    let hi = u64::from(table[(i + 1).min(LEN - 1)]);
    lo + hi.saturating_sub(lo) * f / 1024
}

